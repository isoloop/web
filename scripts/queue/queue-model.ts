// The Publishing queue's model (isoloop/web ADR 0004, decision 7): which merged
// PRs still need a site update, read from and written to one issue's body.
// Pure functions, so the scheduled workflow (publishing-queue.ts) stays thin
// and this file is unit-tested.
import { parseSiteImpact } from '../ci/site-impact-parse.ts';

/** A merged PR, as the scan reads it from the GitHub API. */
export type MergedPr = {
  repo: string;
  number: number;
  title: string;
  mergedAt: string;
  author: string;
  body: string;
};

/** One line of the queue. */
export type QueueItem = {
  repo: string;
  number: number;
  title: string;
  mergedAt: string;
  author: string;
  done: boolean;
  /** Why it's done, when the scan knows: "done in web#N", or the line changed. */
  note?: string;
};

export const MARKER = '<!-- publishing-queue:v1 -->';
export const TITLE = 'Publishing queue';

const key = (repo: string, number: number): string => `${repo}#${number}`;

/** The repo-qualified form the queue prints, e.g. `isoloop/isoloop#212`. */
export const ref = (repo: string, number: number): string => key(repo, number);

/**
 * Reads the items back from an existing queue body. Only lines this module
 * rendered are recognised, so text the maintainer adds around them is ignored
 * (and not kept: the body is regenerated). A ticked box is kept as done.
 */
export function parseQueue(body: string): Map<string, QueueItem> {
  const items = new Map<string, QueueItem>();
  const line =
    /^- \[( |x|X)\] (\S+?)#(\d+) · (.*?) · merged (\d{4}-\d{2}-\d{2}) by @?(\S+?)(?: · (.*))?$/;
  for (const raw of body.split(/\r?\n/)) {
    const m = line.exec(raw.trim());
    if (!m) continue;
    const [, box, repo = '', num = '0', title = '', mergedAt = '', author = '', note] = m;
    const item: QueueItem = {
      repo,
      number: Number(num),
      title,
      mergedAt,
      author,
      done: box !== ' ',
    };
    if (note) item.note = note;
    items.set(key(repo, Number(num)), item);
  }
  return items;
}

/**
 * Folds the scanned PRs into the existing items:
 * - a PR whose Site impact is "update needed" is added, open, if it's new;
 * - a PR whose description now says "done in web#N" is ticked, with that note;
 * - a PR whose line changed to "none" is ticked, noting the change;
 * - an item ticked by hand stays ticked;
 * - items are never dropped, so the queue keeps its history.
 */
export function mergeQueue(existing: Map<string, QueueItem>, scanned: MergedPr[]): QueueItem[] {
  const items = new Map(existing);
  for (const pr of scanned) {
    const k = key(pr.repo, pr.number);
    const impact = parseSiteImpact(pr.body);
    const prev = items.get(k);
    if (!impact.ok) continue;
    if (impact.value === 'update needed') {
      if (!prev) {
        items.set(k, {
          repo: pr.repo,
          number: pr.number,
          title: pr.title,
          mergedAt: pr.mergedAt.slice(0, 10),
          author: pr.author,
          done: false,
        });
      }
      continue;
    }
    if (!prev) continue;
    if (impact.value === 'none') {
      items.set(k, { ...prev, done: true, note: 'Site impact changed to none' });
    } else {
      items.set(k, { ...prev, done: true, note: impact.value });
    }
  }
  return [...items.values()].toSorted(
    (a, b) =>
      Number(a.done) - Number(b.done) ||
      b.mergedAt.localeCompare(a.mergedAt) ||
      a.repo.localeCompare(b.repo) ||
      b.number - a.number,
  );
}

/** One-line titles: no line breaks, and no " · " that would confuse the parser. */
const clean = (s: string): string => s.replace(/\s+/g, ' ').replace(/ · /g, ' - ').trim();

export function renderQueue(items: QueueItem[], opts: { since: string; footer: string[] }): string {
  const open = items.filter((i) => !i.done);
  const done = items.filter((i) => i.done);
  const lineOf = (i: QueueItem): string =>
    `- [${i.done ? 'x' : ' '}] ${ref(i.repo, i.number)} · ${clean(i.title)} · merged ${i.mergedAt} by @${i.author}${i.note ? ` · ${clean(i.note)}` : ''}`;
  const out = [
    MARKER,
    '',
    'Merged PRs whose **Site impact** is `update needed`, in `isoloop/isoloop` and `isoloop/web` ([ADR 0004](https://github.com/isoloop/web/blob/main/docs/adr/0004-publishing-and-governance.md), decision 7). Each one gets a site update through the `publish` skill.',
    '',
    `An item is ticked when its PR's description says \`Site impact: done in web#N\`, or when it's ticked here by hand. This body is regenerated by the Publishing queue workflow every 6 hours; edits outside the checkboxes are not kept. Scanned from ${opts.since}.`,
    '',
    `## Open (${open.length})`,
    '',
    ...(open.length ? open.map(lineOf) : ['Nothing waiting.']),
    '',
    `## Done (${done.length})`,
    '',
    ...(done.length ? done.map(lineOf) : ['Nothing yet.']),
  ];
  if (opts.footer.length) out.push('', '---', '', ...opts.footer);
  return `${out.join('\n')}\n`;
}
