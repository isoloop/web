// The generated API pages (isoloop/isoloop M4c tasks 22–24; ADR 0006): the
// library writes docs/api/<package>.md from its published types, and the site
// renders them like guides, with two changes of its own:
// - the last line, an HTML comment saying the page is generated, is dropped
//   (renderMarkdown has html: false, so it would show as text);
// - an export's `**Experimental.**` lead-in (the first paragraph after its h3)
//   and a member's (the start of its table cell) become the Experimental pill
//   (ADR 0005, decision 4). The text after the lead-in stays.
// The pages' text is never rewritten: the library's docs:check keeps it to the
// docs rules.
import { marks } from '../../src/copy.ts';

/** The generator's note, the page's last line: `<!-- Generated by scripts/docs/api.ts … -->`. */
const GENERATED = /\n<!--\s*Generated\b[^\n]*-->\s*$/;

const PILL = `<span class="ui-pill">${marks.experimental}</span>`;

/** The pill in place of a lead-in: alone, just the pill; followed by text, a space between. */
const lead =
  (end: string) =>
  (_: string, open: string, rest: string): string =>
    rest.startsWith(end) ? `${open}${PILL}${rest}` : `${open}${PILL} ${rest}`;

export const apiPage = {
  /** The page's Markdown without the generator's note. */
  source(src: string): string {
    return src.replace(GENERATED, '\n');
  },

  /** The rendered page with each `**Experimental.**` lead-in as the pill. */
  html(html: string): string {
    return (
      html
        // An export: the paragraph right after its h3.
        .replace(
          /(<\/h3>\n<p) ?>\s*<strong>Experimental\.<\/strong>\s*([\s\S]{0,4})/g,
          (m, open: string, rest: string) =>
            lead('</p>')(m, `${open} class="doc-experimental">`, rest),
        )
        // A member: the start of its table cell.
        .replace(/(<td>)\s*<strong>Experimental\.<\/strong>\s*([\s\S]{0,5})/g, lead('</td>'))
    );
  },
};
